"""(Re)generate vtr.tox from td/src. Run inside TouchDesigner.

Textport:

    exec(open('/path/to/vtr/td/build/build_vtr.py').read())
    build('/path/to/vtr/td')

Idempotent: deletes any existing /vtr COMP, rebuilds it from the spec
(docs/tasks/tox-rework/spec.md + plan.md), embeds the Python source as a
Text DAT (the shipped tox has no filesystem dependency), and saves
td/vtr.tox.
"""

from pathlib import Path

FRAME_EXEC = """# Generated by build_vtr.py — do not edit; edit td/src instead.
def onFrameStart(frame):
    # The guard keeps a half-built comp (aborted build) from spamming the
    # textport every frame.
    try:
        ext = parent().ext.VTRExt
    except AttributeError:
        return
    ext.OnFrame()
    return
"""

PAR_EXEC = """# Generated by build_vtr.py — do not edit; edit td/src instead.
def onValueChange(par, prev):
    parent().ext.VTRExt.OnParChange(par)
    return

def onPulse(par):
    parent().ext.VTRExt.OnPulse(par)
    return
"""

OSC_CALLBACKS = """# Generated by build_vtr.py — do not edit; edit td/src instead.
def onReceiveOSC(dat, rowIndex, message, bytes, timeStamp, address, args, peer):
    parent().ext.VTRExt.OnNotify(address, args)
    return
"""

CHOP_CALLBACKS = """# Generated by build_vtr.py — do not edit; edit td/src instead.
def onCook(scriptOp):
    # Guard a half-built comp (aborted build) — cook fires before the
    # extension is attached.
    try:
        ext = scriptOp.parent().ext.VTRExt
    except AttributeError:
        scriptOp.clear()
        return
    ext.FillChop(scriptOp)
    return
"""

CALLBACKS = """# vtr.tox user callbacks (player mode).
#
# onEvents fires once per frame, before the cook, with the resolved delta
# in order: a list of (port, addr, args) tuples. The state table alone
# would collapse repeated pump events — hook triggers and other
# arrival-sensitive consumers here.
def onEvents(events):
    return
"""

SOCK_DEFAULT = "~/Library/Application Support/VTR/vtr-player.sock"


def _par(pargroup, default):
    p = pargroup[0]
    p.default = default
    p.val = default
    return p


def build(td_dir):
    td_dir = Path(td_dir).expanduser().resolve()
    src = td_dir / "src"

    root = op("/")  # noqa: F821
    if root.op("vtr"):
        root.op("vtr").destroy()
    comp = root.create(baseCOMP, "vtr")  # noqa: F821

    main = comp.appendCustomPage("VTR")
    mode = main.appendMenu("Mode")[0]
    mode.menuNames = ["record", "player"]
    mode.menuLabels = ["Record", "Player"]
    mode.default = "record"
    mode.val = "record"

    rec = comp.appendCustomPage("VTR Rec")
    _par(rec.appendToggle("Clock"), True)
    p = _par(rec.appendFloat("Clockrate"), 10.0)
    p.normMin, p.normMax = 1, 60
    _par(rec.appendStr("Taphost"), "127.0.0.1")
    _par(rec.appendInt("Tapport"), 10010).normMax = 65535
    _par(rec.appendInt("Notifyport"), 10014).normMax = 65535

    play = comp.appendCustomPage("VTR Play")
    _par(play.appendStr("Sockpath"), SOCK_DEFAULT)
    _par(play.appendFile("File"), "")
    play.appendPulse("Reload")
    pm = play.appendMenu("Positionmode")[0]
    pm.menuNames = ["timeline", "follow", "sync", "internal"]
    pm.menuLabels = ["TD Timeline", "Follow Player", "Sync (bidirectional)", "Internal"]
    pm.default = "timeline"
    pm.val = "timeline"
    _par(play.appendFloat("Offset"), 0.0)
    _par(play.appendToggle("Play"), False)
    play.appendPulse("Rewind")
    _par(play.appendStr("Triggerpatterns"), "")

    tap = comp.create(oscoutDAT, "oscout_tap")  # noqa: F821
    tap.par.address.expr = "parent().par.Taphost"
    tap.par.port.expr = "parent().par.Tapport"
    tap.nodeX, tap.nodeY = 0, 200

    occ = comp.create(textDAT, "oscin_callbacks")  # noqa: F821
    occ.text = OSC_CALLBACKS
    occ.nodeX, occ.nodeY = 200, 350

    notify = comp.create(oscinDAT, "oscin_notify")  # noqa: F821
    notify.par.port.expr = "parent().par.Notifyport"
    # Only record mode follows the tap; player mode must not react.
    notify.par.active.expr = "parent().par.Mode == 'record'"
    notify.par.callbacks = "oscin_callbacks"
    notify.nodeX, notify.nodeY = 200, 200

    state = comp.create(tableDAT, "state")  # noqa: F821
    state.clear()
    state.appendRow(["port", "addr"])
    state.nodeX, state.nodeY = 400, 200

    info = comp.create(tableDAT, "info")  # noqa: F821
    info.clear()
    info.appendRow(["name", "value"])
    info.nodeX, info.nodeY = 400, 350

    chc = comp.create(textDAT, "chop_callbacks")  # noqa: F821
    chc.text = CHOP_CALLBACKS
    chc.nodeX, chc.nodeY = 200, -150

    chop = comp.create(scriptCHOP, "chop_out")  # noqa: F821
    chop.par.callbacks = "chop_callbacks"
    chop.nodeX, chop.nodeY = 400, -150

    cb = comp.create(textDAT, "callbacks")  # noqa: F821
    cb.text = CALLBACKS
    cb.nodeX, cb.nodeY = 400, 50

    dat = comp.create(textDAT, "ext_vtr")  # noqa: F821
    dat.text = (src / "vtr_ext.py").read_text(encoding="utf-8")
    dat.nodeX, dat.nodeY = -400, 0

    fe = comp.create(executeDAT, "exec_frame")  # noqa: F821
    fe.par.framestart = True
    fe.text = FRAME_EXEC
    fe.nodeX, fe.nodeY = 0, 0

    pe = comp.create(parameterexecuteDAT, "parexec_pars")  # noqa: F821
    pe.par.op = ".."
    pe.par.pars = "*"
    pe.par.valuechange = True
    pe.par.onpulse = True
    pe.text = PAR_EXEC
    pe.nodeX, pe.nodeY = 0, -150

    comp.par.extension1 = "op('./ext_vtr').module.VTRExt(me)"
    comp.par.promoteextension1 = True
    comp.initializeExtensions()

    out = td_dir / "vtr.tox"
    comp.save(str(out))
    print("VTR: saved", out)
    return comp
