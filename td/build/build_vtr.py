"""(Re)generate vtr.tox from td/src. Run inside TouchDesigner.

Textport:

    exec(open('/path/to/vtr/td/build/build_vtr.py').read())
    build('/path/to/vtr/td')

Idempotent: deletes any existing /vtr COMP, rebuilds it from the spec
(docs/tasks/td/spec.md), embeds the Python sources as Text DATs (the shipped
tox has no filesystem dependency), and saves td/vtr.tox.
"""

from pathlib import Path

FRAME_EXEC = """# Generated by build_vtr.py — do not edit; edit td/src instead.
def onFrameStart(frame):
    parent().ext.VTRExt.OnFrame()
    return
"""

PAR_EXEC = """# Generated by build_vtr.py — do not edit; edit td/src instead.
def onValueChange(par, prev):
    parent().ext.VTRExt.OnParChange(par)
    return

def onPulse(par):
    parent().ext.VTRExt.OnPulse(par)
    return
"""

# (DAT name, path under td/src). ext_vtr resolves the core DATs via mod().
SOURCES = [
    ("ext_vtr", "vtr_ext.py"),
    ("core_session", "vtr_core/session.py"),
    ("core_resolver", "vtr_core/resolver.py"),
]


def _par(pargroup, default):
    p = pargroup[0]
    p.default = default
    p.val = default
    return p


def build(td_dir):
    td_dir = Path(td_dir).expanduser().resolve()
    src = td_dir / "src"

    root = op("/")  # noqa: F821
    if root.op("vtr"):
        root.op("vtr").destroy()
    comp = root.create(baseCOMP, "vtr")  # noqa: F821

    rec = comp.appendCustomPage("VTR Rec")
    _par(rec.appendToggle("Record"), False)
    _par(rec.appendToggle("Clock"), True)
    p = _par(rec.appendFloat("Clockrate"), 10.0)
    p.normMin, p.normMax = 1, 60
    _par(rec.appendStr("Controlhost"), "127.0.0.1")
    _par(rec.appendInt("Controlport"), 10012).normMax = 65535

    play = comp.appendCustomPage("VTR Play")
    _par(play.appendFile("File"), "")
    _par(play.appendToggle("Locktotimeline"), True)
    _par(play.appendFloat("Offset"), 0.0)
    _par(play.appendToggle("Play"), False)
    play.appendPulse("Rewind")
    _par(play.appendStr("Triggerpatterns"), "")
    _par(play.appendStr("Playhost"), "")
    _par(play.appendInt("Playport"), 0).normMax = 65535

    ctrl = comp.create(oscoutDAT, "oscout_ctrl")  # noqa: F821
    ctrl.par.address.expr = "parent().par.Controlhost"
    ctrl.par.port.expr = "parent().par.Controlport"
    ctrl.nodeX, ctrl.nodeY = 0, 200

    for i, (name, rel) in enumerate(SOURCES):
        dat = comp.create(textDAT, name)  # noqa: F821
        dat.text = (src / rel).read_text(encoding="utf-8")
        dat.nodeX, dat.nodeY = -400, -i * 150

    fe = comp.create(executeDAT, "exec_frame")  # noqa: F821
    fe.par.framestart = True
    fe.text = FRAME_EXEC
    fe.nodeX, fe.nodeY = 0, 0

    pe = comp.create(parexecDAT, "parexec_pars")  # noqa: F821
    pe.par.op = ".."
    pe.par.pars = "*"
    pe.par.valuechange = True
    pe.par.onpulse = True
    pe.text = PAR_EXEC
    pe.nodeX, pe.nodeY = 0, -150

    comp.par.extension1 = "op('./ext_vtr').module.VTRExt(me)"
    comp.par.promoteextension1 = True
    comp.initializeExtensions()

    out = td_dir / "vtr.tox"
    comp.save(str(out))
    print("VTR: saved", out)
    return comp
